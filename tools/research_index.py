#!/usr/bin/env python3
"""Generator, validator, scaffolder and query tool for the research spine.

A study is any scripts/<S>/research/study_config.json (today: mrd_stage0_2). For each study
the tool parses the hand-maintained spine (THEME.md, hypotheses.md, alternatives.csv,
analyses.csv, campaigns.csv, asks/*.md, devlog/<YYYY>/*.md and workstreams/W*_*/README.md),
derives verdicts, alternative states, task and ask states and reverse links, and renders
the three generated views research/STATUS.md, research/CLAIMS.md and research/devlog/INDEX.md.

Usage (from the repo root):
    python tools/research_index.py [check] [--strict] [--strict-artifacts]
                                   [--experiment-root DIR] [--study S]
    python tools/research_index.py write [--study S]
    python tools/research_index.py new-entry SLUG --workstream W# [--type analysis]
                                   [--analyses ID ...] [--asks A-... ...] [--date YYYY-MM-DD]
    python tools/research_index.py reserve-id --workstream W# --title 'TEXT'
                                   [--questions 'Q1;Q2'] [--slug SLUG_vN] [--asks 'A-...;A-...']
                                   [--code 'path;path'] [--findings-md FILE]
    python tools/research_index.py show ID [--git]
    python tools/research_index.py portability

Exit codes: 0 ok; 1 validation errors; 2 usage error; 3 generated files stale.
--strict promotes warnings to errors except W11 (history on backfilled entries, never cleared).
--strict-artifacts promotes W10 to an error and fails (E21) when the experiment dir does not
resolve, so a wrong SC_EXPERIMENT_ROOT / SC_EXPERIMENT_ID never passes silently.

Stdlib only; Python >= 3.8. Generated files are deterministic: sorted, LF line endings, no
wall-clock time ('as of' is the latest date found in the inputs), written atomically. The
SC_* variables are resolved by src/sc_classification/utils/paths.py, loaded by file path,
so the package need not be installed. Never add absolute or home-relative paths to this
file (lint E07 covers tools/**). Changes go through a devlog entry with type: refactor and
must keep tests/test_research_index.py passing.
"""

