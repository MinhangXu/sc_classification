def overlay_files(repo: Path, studies: Sequence[str]) -> List[Path]:
    files: List[Path] = []
    for name in OVERLAY_FILES:
        if (repo / name).is_file():
            files.append(repo / name)
    files += sorted((repo / ".cursor" / "rules").glob("*.mdc")) if (repo / ".cursor" / "rules").is_dir() else []
    files += walk_files(repo / "tools")
    for study in studies:
        research = repo / "scripts" / study / "research"
        files += [p for p in walk_files(research) if not p.relative_to(research).parts[0] == "legacy"]
        files += walk_files(repo / "scripts" / study / "workstreams")
    return sorted(set(files))


def lint_absolute_paths(repo: Path, studies: Sequence[str], report: Report) -> None:
    for path in overlay_files(repo, studies):
        try:
            raw = path.read_bytes()
        except OSError:
            continue
        if b"\x00" in raw[:8192]:
            continue
        for i, line in enumerate(raw.decode("utf-8", errors="replace").split("\n")):
            hits = [n for n in ABS_NEEDLES if n in line]
            if RE_DRIVE.search(line):
                hits.append("drive letter")
            if hits:
                report.add("E07", path, i + 1, "absolute or home path (%s) in an overlay file; use repo-relative, "
                           "EXP-relative or $SC_* paths" % ", ".join(repr(h) for h in hits))


