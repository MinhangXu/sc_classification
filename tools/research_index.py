class Derived:
    def __init__(self, st: Study) -> None:
        self.st = st
        ents = st.entries
        self.superseded_by: Dict[str, List[str]] = {}
        for e in ents:
            for target in e.lst("supersedes"):
                self.superseded_by.setdefault(target, []).append(e.id)
        self.superseded: Set[str] = set(self.superseded_by) | {e.id for e in ents if e.status == "superseded"}
        self.verdict_hist: Dict[str, List[Tuple[str, str, str]]] = {}
        self.alt_hist: Dict[Tuple[str, str], List[Tuple[str, str, str]]] = {}
        for e in ents:
            for token in e.lst("verdicts"):
                m = RE_VERDICT_TOKEN.match(token)
                if m and m.group(2) in VERDICTS:
                    self.verdict_hist.setdefault(m.group(1), []).append((e.date, e.id, m.group(2)))
            for token in e.lst("alts"):
                m = RE_ALT_TOKEN.match(token)
                if m and m.group(3) in ALT_STATES:
                    self.alt_hist.setdefault((m.group(1), m.group(2)), []).append((e.date, e.id, m.group(3)))
        self.evidence: Dict[str, List[Evidence]] = {}
        self.evidence_all: Dict[str, List[Evidence]] = {}
        for e in ents:
            for ev in e.evidence:
                self.evidence_all.setdefault(ev.hyp, []).append(ev)
                if e.id not in self.superseded:
                    self.evidence.setdefault(ev.hyp, []).append(ev)
        # tasks
        self.task_citers: Dict[str, List[Entry]] = {}
        done: Set[str] = set()
        progress: Set[str] = set()
        for e in ents:
            for tid in e.lst("closes"):
                self.task_citers.setdefault(tid, []).append(e)
                if e.status == "done":
                    done.add(tid)
                elif e.status == "partial":
                    progress.add(tid)
            for tid in e.lst("advances"):
                self.task_citers.setdefault(tid, []).append(e)
                progress.add(tid)
        self.task_state: Dict[str, str] = {}
        for tid, task in st.tasks.items():
            if tid in done:
                state = "done"
            elif task.blocked:
                state = "blocked"
            elif tid in progress:
                state = "in_progress"
            else:
                state = "open"
            self.task_state[tid] = state
        # asks
        self.ask_citers: Dict[str, List[Entry]] = {}
        for e in ents:
            for aid in e.lst("asks"):
                self.ask_citers.setdefault(aid, []).append(e)
        self.ask_state: Dict[str, str] = {}
        for aid, ask in st.asks.items():
            citers = self.ask_citers.get(aid, [])
            routed = [r for r in ask.routes if RE_TASK.match(r)]
            answered = any(e.status == "done" and e.type in ANSWER_TYPES for e in citers) and all(
                self.task_state.get(t) == "done" for t in routed)
            if answered:
                state = "answered"
            elif any(e.type != "meeting" for e in citers) or any(self.task_state.get(t, "open") != "open" for t in routed):
                state = "partial"
            else:
                state = "open"
            self.ask_state[aid] = state
        # reverse links
        self.analysis_citers: Dict[str, List[Entry]] = {}
        self.ws_entries: Dict[str, List[Entry]] = {}
        self.hyp_citers: Dict[str, List[Entry]] = {}
        for e in ents:
            for aid in e.lst("analyses"):
                self.analysis_citers.setdefault(aid, []).append(e)
            ws = str(e.val("workstream"))
            if ws:
                self.ws_entries.setdefault(ws, []).append(e)
            hyps = set(e.lst("hypotheses")) | {ev.hyp for ev in e.evidence}
            hyps |= {t.split("=")[0] for t in e.lst("verdicts")} | {t.split(":")[0] for t in e.lst("alts")}
            for hid in hyps:
                self.hyp_citers.setdefault(hid, []).append(e)
        self.analysis_hyps: Dict[str, List[str]] = {}
        for hid in sorted(st.hyps, key=hyp_key):
            for aid in st.hyps[hid].lst("analyses"):
                self.analysis_hyps.setdefault(aid, []).append(hid)
        self.ws_last = {ws: es[-1].date for ws, es in self.ws_entries.items()}
        last_reviewed = str(st.theme_fm.get("last_reviewed", ""))
        self.theme_queue = self.review_queue(st, ents, last_reviewed)
        dates = [e.date for e in ents] + [r.get("date", "") for r in st.analyses.values()] + st.ask_file_dates + [last_reviewed]
        dates = [x for x in dates if valid_date(x)]
        self.as_of = max(dates) if dates else "unknown"
        nums = [int(m.group(1)) for m in (RE_D_NUM.match(a) for a in st.analyses) if m]
        self.next_d = "D%d" % ((max(nums) if nums else 0) + 1)

    @staticmethod
    def review_queue(st: "Study", ents: Sequence["Entry"], last_reviewed: str) -> List["Entry"]:
        """Entries with verdicts, alternative states or evidence that THEME has not reviewed yet.

        With THEME front matter reviewed_through: <devlog id>, every such entry after that id in
        chronological (INDEX) order. Otherwise every such entry dated after last_reviewed, plus the
        ones dated on last_reviewed that THEME.md does not cite by id (so same-day verdict changes
        are not hidden)."""
        relevant = [e for e in ents if e.lst("verdicts") or e.lst("alts") or e.evidence]
        through = str(st.theme_fm.get("reviewed_through", "") or "").strip()
        if through and through in st.entry_by_id:
            mark = entry_sort_key(st.entry_by_id[through])
            return [e for e in relevant if entry_sort_key(e) > mark]
        if not valid_date(last_reviewed):
            return []
        theme_text = "\n".join(st.theme_lines)
        return [e for e in relevant if e.date > last_reviewed or (e.date == last_reviewed and e.id not in theme_text)]

    def verdict(self, hid: str) -> Tuple[str, str, str]:
        hist = self.verdict_hist.get(hid)
        return hist[-1] if hist else ("", "", "none")

    def alt_state(self, hid: str, alt: str) -> str:
        hist = self.alt_hist.get((hid, alt))
        return hist[-1][2] if hist else "open"

    def gate(self, hid: str) -> List[Tuple[str, bool]]:
        st, h = self.st, self.st.hyps[hid]
        alts = h.lst("alternatives")
        blocking = h.lst("blocking")
        clean = False
        for ev in self.evidence.get(hid, []):
            e = st.entry_by_id.get(ev.entry_id)
            if ev.role == "supports" and e is not None and RE_HEX.match(str(e.fm.get("commit", ""))) and e.fm.get("dirty_run") is not True:
                clean = True
        _, decl_id, verdict = self.verdict(hid)
        decl = st.entry_by_id.get(decl_id)
        return [
            ("alternatives addressed %d/%d" % (sum(self.alt_state(hid, a) == "addressed" for a in alts), len(alts)),
             all(self.alt_state(hid, a) == "addressed" for a in alts)),
            ("blocking done %d/%d" % (sum(self.task_state.get(t) == "done" for t in blocking), len(blocking)),
             all(self.task_state.get(t) == "done" for t in blocking)),
            ("supports bullet from a clean hex commit", clean),
            ("figures listed", bool(h.lst("figures"))),
            ("declaring entry has claim_level: publication",
             verdict == "supported_publication" and decl is not None and decl.fm.get("claim_level") == "publication"),
        ]

    def last_task_citer(self, tid: str) -> Optional[Entry]:
        es = self.task_citers.get(tid, [])
        return es[-1] if es else None


