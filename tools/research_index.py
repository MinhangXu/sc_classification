@dataclasses.dataclass
class FrontMatter:
    data: Dict[str, Any]
    lines: Dict[str, int]
    body_start: int  # 0-based index of the first body line
    ok: bool


def parse_front_matter(lines: Sequence[str], rel: Any, report: Report) -> FrontMatter:
    if not lines or lines[0].rstrip() != "---":
        report.add("E01", rel, 1, "missing front matter: the first line must be '---' (%s)" % FM_HINT)
        return FrontMatter({}, {}, 0, False)
    data: Dict[str, Any] = {}
    where: Dict[str, int] = {}
    ok = True
    for i in range(1, len(lines)):
        raw = lines[i]
        if raw.rstrip() == "---":
            return FrontMatter(data, where, i + 1, ok)
        if not raw.strip():
            continue
        problem = None
        if raw[0] in " \t":
            problem = "indented line (nesting or block list) is not allowed"
        elif raw.startswith("- ") or raw.strip() == "-":
            problem = "block list item; use an inline list [a, b]"
        else:
            m = RE_FM_LINE.match(raw)
            if not m:
                problem = "cannot parse %r; expected 'key: value' with a lowercase key" % raw.strip()
            else:
                key, value = m.group(1), m.group(2).strip()
                if value[:1] in ("|", ">"):
                    problem = "multi-line value ('%s') is not allowed" % value[:1]
                elif value[:1] == "{":
                    problem = "nested mapping is not allowed"
                elif key in data:
                    problem = "duplicate key %r" % key
                else:
                    data[key] = parse_value(value)
                    where[key] = i + 1
        if problem:
            ok = False
            report.add("E01", rel, i + 1, "%s (%s)" % (problem, FM_HINT))
    report.add("E01", rel, 1, "unterminated front matter: no closing '---' (%s)" % FM_HINT)
    return FrontMatter(data, where, len(lines), False)


def split_sections(lines: Sequence[str], start: int) -> List[Tuple[str, int, List[Tuple[int, str]]]]:
    """Split body lines on '## ' headings outside fenced blocks: [(heading, idx, [(idx, line)])]."""
    sections: List[Tuple[str, int, List[Tuple[int, str]]]] = []
    fence = False
    for i in range(start, len(lines)):
        line = lines[i]
        if RE_FENCE.match(line):
            fence = not fence
        elif not fence:
            m = RE_H2.match(line)
            if m:
                sections.append((m.group(1).strip(), i, []))
                continue
        if sections:
            sections[-1][2].append((i, line))
    return sections


def unfenced(lines: Iterable[Tuple[int, str]]) -> List[Tuple[int, str]]:
    out: List[Tuple[int, str]] = []
    fence = False
    for i, line in lines:
        if RE_FENCE.match(line):
            fence = not fence
            continue
        if not fence:
            out.append((i, line))
    return out


def path_tokens(line: str) -> List[str]:
    """Path-like tokens of a markdown line (contain '/', not URLs), cleaned of markup."""
    out = []
    for raw in re.split(r"\s+", re.sub(r"^\s*[-*+]\s+", "", line)):
        token = raw.strip("`'\"()[]<>,;:")
        if token.endswith("."):
            token = token[:-1]
        if len(token) < 2 or "/" not in token or "://" in token:
            continue
        out.append(token)
    return out


