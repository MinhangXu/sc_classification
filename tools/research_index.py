def discover(repo: Path) -> List[str]:
    scripts = repo / "scripts"
    if not scripts.is_dir():
        return []
    return sorted(p.parent.parent.name for p in scripts.glob("*/research/study_config.json"))


def resolve_exp(repo: Path, st: Study, experiment_root: Optional[str]) -> Optional[Path]:
    paths = load_paths_module(repo)
    var = getattr(paths, "ENV_EXPERIMENT_ID", "SC_EXPERIMENT_ID")
    exp_id = os.environ.get(var, "").strip() or st.canonical_id
    root: Optional[Path] = None
    if experiment_root:
        root = Path(experiment_root)
    elif paths is not None:
        try:
            root = Path(paths.experiment_root())
        except Exception:
            root = None
    else:
        root = repo / "experiments"
    if not exp_id or root is None:
        return None
    exp = root / exp_id
    return exp if exp.is_dir() else None


def walk_files(base: Path) -> List[Path]:
    out: List[Path] = []
    if base.is_file():
        return [base]
    if not base.is_dir():
        return out
    for dirpath, dirnames, filenames in os.walk(str(base)):
        dirnames[:] = sorted(n for n in dirnames if n not in SKIP_DIRS)
        out.extend(Path(dirpath) / f for f in sorted(filenames))
    return out


