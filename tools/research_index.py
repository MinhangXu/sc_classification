@dataclasses.dataclass(frozen=True)
class Issue:
    code: str
    path: str
    line: int
    msg: str

    def render(self) -> str:
        loc = self.path + (":%d" % self.line if self.line else "")
        return "%s %s: %s" % (self.code, loc, self.msg)

    def sort_key(self) -> Tuple[str, int, str, str]:
        return (self.path, self.line, self.code, self.msg)


class Report:
    def __init__(self, repo: Path) -> None:
        self.repo = repo
        self.issues: List[Issue] = []
        self.stale: List[Tuple[str, str]] = []  # (relpath, diff)

    def rel(self, path: Any) -> str:
        if isinstance(path, Path):
            try:
                return path.relative_to(self.repo).as_posix()
            except ValueError:
                return path.as_posix()
        return str(path)

    def add(self, code: str, path: Any, line: Optional[int], msg: str) -> None:
        self.issues.append(Issue(code, self.rel(path), int(line or 0), msg))


