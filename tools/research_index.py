def build_parser() -> argparse.ArgumentParser:
    epilog = "codes:\n" + "\n".join("  %s %s" % (k, v) for k, v in CODES.items())
    parser = argparse.ArgumentParser(prog="research_index.py", description="Research spine generator, validator and query tool.",
                                     epilog=epilog, formatter_class=argparse.RawDescriptionHelpFormatter)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--repo", help=argparse.SUPPRESS)
    common.add_argument("--study", help="narrow the run to one study (scripts/<S>)")
    sub = parser.add_subparsers(dest="cmd")
    for name in ("check", "write"):
        p = sub.add_parser(name, parents=[common], help="validate the spine" if name == "check" else "regenerate STATUS/CLAIMS/INDEX, then check")
        p.add_argument("--strict", action="store_true", help="treat warnings as errors (except W11, which records history)")
        p.add_argument("--strict-artifacts", action="store_true",
                       help="missing artifacts (W10) are errors, and an unresolvable experiment dir is an error (E21)")
        p.add_argument("--experiment-root", help="directory holding experiment dirs (overrides SC_EXPERIMENT_ROOT)")
        p.add_argument("--today", help="reference date YYYY-MM-DD for the time-based warnings (default: UTC today)")
    p = sub.add_parser("new-entry", parents=[common], help="scaffold research/devlog/<YYYY>/<date>_<slug>.md")
    p.add_argument("slug")
    p.add_argument("--workstream", required=True)
    p.add_argument("--type", default="analysis")
    p.add_argument("--analyses", nargs="*", default=[])
    p.add_argument("--asks", nargs="*", default=[])
    p.add_argument("--date", help="YYYY-MM-DD (default: UTC today)")
    p = sub.add_parser("reserve-id", parents=[common], help="append a planned D row with the next free number")
    p.add_argument("--workstream", required=True)
    p.add_argument("--title", required=True)
    p.add_argument("--questions", help="';'-separated, e.g. 'Q1;Q2'")
    p.add_argument("--question", help="the research question in one sentence (number-free)")
    p.add_argument("--slug", help="artifact slug ending in _v<N>")
    p.add_argument("--asked-by", default="not_recorded")
    p.add_argument("--asks", help="';'-separated ask ids the analysis answers, e.g. 'A-20261008-21'")
    p.add_argument("--code", help="';'-separated repo-relative code paths (the runner may not exist yet)")
    p.add_argument("--findings-md", help="findings file: a name inside --slug, or a path relative to the experiment dir")
    p.add_argument("--date", help="YYYY-MM-DD (default: UTC today)")
    p = sub.add_parser("show", parents=[common], help="print a record and everything linked to it")
    p.add_argument("id")
    p.add_argument("--git", action="store_true", help="add the last commit touching each code path")
    sub.add_parser("portability", parents=[common], help="list legacy files embedding absolute home paths")
    return parser


def main(argv: Optional[Sequence[str]] = None, repo: Optional[Path] = None) -> int:
    args_list = list(sys.argv[1:] if argv is None else argv)
    commands = ("check", "write", "new-entry", "reserve-id", "show", "portability")
    if not any(a in commands for a in args_list[:1]) and not any(a in ("-h", "--help") for a in args_list[:1]):
        args_list = ["check"] + args_list
    args = build_parser().parse_args(args_list)
    root = Path(args.repo).resolve() if getattr(args, "repo", None) else (repo or REPO_DEFAULT)
    today_arg = getattr(args, "today", None)
    if today_arg and not valid_date(today_arg):
        print("--today must be YYYY-MM-DD", file=sys.stderr)
        return 2
    today = to_date(today_arg) if today_arg else datetime.datetime.now(datetime.timezone.utc).date()
    if not discover(root):
        print("no studies found")
        return 0
    if args.cmd == "portability":
        return cmd_portability(root)
    if args.cmd == "new-entry":
        return cmd_new_entry(root, args, today)  # type: ignore[arg-type]
    if args.cmd == "reserve-id":
        return cmd_reserve_id(root, args, today)  # type: ignore[arg-type]
    if args.cmd == "show":
        return cmd_show(root, args)
    names = load_studies(root, args.study)
    if names is None:
        return 2
    ctx = Context(root, today, None, args.strict, args.strict_artifacts)  # type: ignore[arg-type]
    if args.cmd == "write":
        return cmd_write(ctx, names, args.experiment_root)
    return run_check(ctx, names, args.experiment_root)


if __name__ == "__main__":
    sys.exit(main())
