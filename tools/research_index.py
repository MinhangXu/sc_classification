def read_lines(path: Path) -> List[str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    return text.replace("\r\n", "\n").replace("\r", "\n").split("\n")


def is_todo(value: Any) -> bool:
    if isinstance(value, str):
        return value.strip().startswith("TODO")
    if isinstance(value, list):
        return any(isinstance(v, str) and v.strip().startswith("TODO") for v in value)
    return False


def parse_value(raw: str) -> Any:
    value = raw.strip()
    m = RE_LIST_VALUE.match(value)
    if m:
        inner = m.group(1).strip()
        return [item.strip() for item in inner.split(",") if item.strip()] if inner else []
    if value == "true":
        return True
    if value == "false":
        return False
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def split_list(cell: str, seps: str = ";") -> List[str]:
    if not cell:
        return []
    return [part.strip() for part in re.split("[" + re.escape(seps) + "]", cell) if part.strip()]


def valid_date(value: Any) -> bool:
    if not isinstance(value, str) or not RE_DATE.match(value):
        return False
    try:
        datetime.date(int(value[:4]), int(value[5:7]), int(value[8:10]))
    except ValueError:
        return False
    return True


def to_date(value: str) -> Optional[datetime.date]:
    return datetime.date(int(value[:4]), int(value[5:7]), int(value[8:10])) if valid_date(value) else None


def fmt_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    if isinstance(value, dict):
        return json.dumps(value, sort_keys=True)
    return str(value)


def cell(value: Any) -> str:
    return fmt_value(value).replace("|", "\\|").replace("\n", " ").strip()


def trunc(text: str, n: int) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"


def task_key(tid: str) -> Tuple[int, int, str]:
    m = re.match(r"^W(\d+)\.(\d+)$", tid)
    return (int(m.group(1)), int(m.group(2)), "") if m else (10 ** 6, 0, tid)


def hyp_key(hid: str) -> Tuple[int, int, str]:
    m = re.match(r"^H-(S0|S1|S2|I|A)-(\d{2})$", hid)
    return (HYP_STAGE_ORDER[m.group(1)], int(m.group(2)), "") if m else (99, 0, hid)


def analysis_family(aid: str) -> Optional[str]:
    if aid == "V2":
        return "V2"
    if re.match(r"^D1DD\d+$", aid):
        return "D1DD"
    if re.match(r"^D\d+[a-z]?$", aid):
        return "D"
    if re.match(r"^F\d+$", aid):
        return "F"
    return None


def analysis_key(aid: str) -> Tuple[int, int, str]:
    fam = analysis_family(aid)
    num = re.search(r"(\d+)([a-z]?)$", aid)
    n, suffix = (int(num.group(1)), num.group(2)) if num else (0, "")
    order = {"V2": 0, "D": 1, "D1DD": 2, "F": 3}.get(fam or "", 4)
    return (order, 0 if fam == "V2" else n, suffix if fam == "D" else aid)


def entry_seq(entry: "Entry") -> int:
    """Optional same-day tie-breaker (front-matter key seq: <int>, default 0)."""
    raw = str(entry.fm.get("seq", "0") if entry.fm else "0").strip()
    return int(raw) if re.match(r"^\d{1,4}$", raw) else 0


def entry_sort_key(entry: "Entry") -> Tuple[str, int, str]:
    """Chronological order: date, then the optional seq (default 0), then id. Same-date entries
    without seq therefore resolve alphabetically by id; give the entry that must win a higher seq."""
    return (entry.date, entry_seq(entry), entry.id)


def number_tokens(text: str) -> List[str]:
    stripped = RE_ID_LIKE.sub(" ", text)
    return [m.group(0).strip() for m in RE_NUMBERISH.finditer(stripped)]


def atomic_write(path: Path, text: str) -> bool:
    """Write text with LF endings through a temp file; return True if the file changed."""
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name("." + path.name + ".tmp-%d" % os.getpid())
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(str(tmp), str(path))
    return True


def git(repo: Path, *args: str) -> Optional[str]:
    try:
        proc = subprocess.run(["git", "-C", str(repo)] + list(args), stdout=subprocess.PIPE,
                              stderr=subprocess.DEVNULL, universal_newlines=True, timeout=60, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    return proc.stdout if proc.returncode == 0 else None


def load_paths_module(repo: Path) -> Any:
    """Load src/sc_classification/utils/paths.py by file path (target repo first)."""
    for candidate in (repo / PATHS_REL, REPO_DEFAULT / PATHS_REL):
        if not candidate.is_file():
            continue
        spec = importlib.util.spec_from_file_location("_research_index_paths", str(candidate))
        if spec is None or spec.loader is None:
            continue
        module = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(module)  # type: ignore[union-attr]
        except Exception:
            continue
        return module
    return None


