class Study:
    def __init__(self, repo: Path, name: str, report: Report) -> None:
        self.repo = repo
        self.name = name
        self.report = report
        self.dir = repo / "scripts" / name
        self.research = self.dir / "research"
        self.devlog_dir = self.research / "devlog"
        self.config: Dict[str, Any] = {}
        self.theme_fm: Dict[str, Any] = {}
        self.theme_lines: List[str] = []
        self.theme_body_start = 0
        self.hyps: Dict[str, Hypothesis] = {}
        self.alts: Dict[str, Dict[str, str]] = {}
        self.alt_lines: Dict[str, int] = {}
        self.analyses: Dict[str, Dict[str, str]] = {}
        self.analysis_lines: Dict[str, int] = {}
        self.campaigns: List[Dict[str, str]] = []
        self.asks: Dict[str, Ask] = {}
        self.ask_file_dates: List[str] = []
        self.entries: List[Entry] = []
        self.entry_by_id: Dict[str, Entry] = {}
        self.workstreams: Dict[str, Workstream] = {}
        self.tasks: Dict[str, Task] = {}
        self.template: Optional[Path] = None

    # ----------------------------------------------------------------------- utilities
    def add(self, code: str, path: Any, line: Optional[int], msg: str) -> None:
        self.report.add(code, path, line, msg)

    def rel(self, path: Path) -> str:
        return self.report.rel(path)

    def need(self, path: Path) -> bool:
        if path.is_file():
            return True
        self.add("E02", path, 0, "required file is missing")
        return False

    @property
    def canonical_id(self) -> str:
        return str(self.config.get("canonical_experiment_id", "") or "")

    def read_csv(self, path: Path, header: List[str], code: str) -> List[Tuple[int, Dict[str, str]]]:
        if not self.need(path):
            return []
        rows: List[Tuple[int, Dict[str, str]]] = []
        with open(path, newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh)
            fields = list(reader.fieldnames or [])
            if fields != header:
                self.add(code, path, 1, "header mismatch: expected %s; found %s" % (",".join(header), ",".join(fields)))
            for row in reader:
                if None in row:
                    self.add(code, path, reader.line_num, "row has more fields than the header")
                rows.append((reader.line_num, {k: (v or "").strip() for k, v in row.items()
                                               if k is not None and isinstance(v, (str, type(None)))}))
        return rows

    # ----------------------------------------------------------------------- loading
    def load(self) -> "Study":
        cfg_path = self.research / "study_config.json"
        try:
            data = json.loads(cfg_path.read_text(encoding="utf-8"))
            self.config = data if isinstance(data, dict) else {}
            if not isinstance(data, dict):
                self.add("E01", cfg_path, 1, "study_config.json must hold a JSON object")
        except ValueError as exc:
            self.add("E01", cfg_path, 1, "malformed JSON: %s" % exc)
        self.load_theme()
        self.load_alternatives()
        self.load_workstreams()
        self.load_analyses()
        self.load_campaigns()
        self.load_hypotheses()
        self.load_asks()
        self.load_devlog()
        return self

    def load_theme(self) -> None:
        path = self.research / "THEME.md"
        if not self.need(path):
            return
        self.theme_lines = read_lines(path)
        fm = parse_front_matter(self.theme_lines, path, self.report)
        self.theme_fm, self.theme_body_start = fm.data, fm.body_start
        if not fm.ok and fm.body_start == 0:
            return
        for key in THEME_KEYS:
            if key not in fm.data:
                self.add("E02", path, 1, "THEME front matter misses %r" % key)
        for key in sorted(set(fm.data) - set(THEME_KEYS) - set(THEME_KEYS_OPTIONAL)):
            self.add("E02", path, fm.lines[key], "unknown THEME front-matter key %r" % key)
        if "last_reviewed" in fm.data and not valid_date(fm.data["last_reviewed"]):
            self.add("E02", path, fm.lines["last_reviewed"], "last_reviewed must be YYYY-MM-DD")
        if self.canonical_id and fm.data.get("canonical_experiment") not in (None, self.canonical_id):
            self.add("E02", path, fm.lines.get("canonical_experiment", 1),
                     "canonical_experiment differs from study_config canonical_experiment_id")

    def load_alternatives(self) -> None:
        path = self.research / "alternatives.csv"
        for line, row in self.read_csv(path, ALT_HEADER, "E19"):
            aid = row.get("alt_id", "")
            if not RE_ALT_ID.match(aid):
                self.add("E02", path, line, "alt_id %r must match ALT-<NAME>" % aid)
                continue
            if aid in self.alts:
                self.add("E05", path, line, "duplicate alternative %s" % aid)
                continue
            self.alts[aid] = row
            self.alt_lines[aid] = line

    def load_workstreams(self) -> None:
        base = self.dir / "workstreams"
        if not base.is_dir():
            return
        for wdir in sorted(p for p in base.iterdir() if p.is_dir() and re.match(r"^W\d+_", p.name)):
            path = wdir / "README.md"
            if not path.is_file():
                self.add("E18", wdir, 0, "workstream directory has no README.md")
                continue
            lines = read_lines(path)
            fm = parse_front_matter(lines, path, self.report)
            prefix = wdir.name.split("_", 1)[0]
            for key in WS_KEYS:
                if key not in fm.data:
                    self.add("E18", path, 1, "front matter misses %r" % key)
            for key in sorted(set(fm.data) - set(WS_KEYS)):
                self.add("E18", path, fm.lines[key], "unknown front-matter key %r" % key)
            wid = str(fm.data.get("id", ""))
            if wid != prefix:
                self.add("E18", path, fm.lines.get("id", 1), "id %r must equal the directory prefix %r" % (wid, prefix))
            if "status" in fm.data and fm.data["status"] not in WS_STATUS:
                self.add("E18", path, fm.lines["status"], "status %r not in %s" % (fm.data["status"], "|".join(WS_STATUS)))
            qs = fm.data.get("questions")
            if "questions" in fm.data and (not isinstance(qs, list) or not qs or any(q not in Q_TAGS for q in qs)):
                self.add("E18", path, fm.lines["questions"], "questions must be a non-empty inline list from %s" % ", ".join(Q_TAGS))
            if prefix in self.workstreams:
                self.add("E05", path, 1, "duplicate workstream %s" % prefix)
                continue
            ws = Workstream(prefix, wdir.name, self.rel(path), fm.data, [])
            self.workstreams[prefix] = ws
            self.parse_backlog(ws, path, lines, fm.body_start)

    def parse_backlog(self, ws: Workstream, path: Path, lines: List[str], start: int) -> None:
        for heading, _, body in split_sections(lines, start):
            if heading != "Backlog":
                continue
            for i, line in unfenced(body):
                if not line.startswith("- ["):
                    continue
                m = RE_TASK_LINE.match(line)
                if not m:
                    self.add("E18", path, i + 1, "malformed backlog line; expected '- [W#.n] (P0|P1|P2|P3|later) text'")
                    continue
                tid, prio, rest = m.group(1).strip(), m.group(2).strip(), m.group(3).strip()
                if not RE_TASK.match(tid) or not tid.startswith(ws.id + "."):
                    self.add("E18", path, i + 1, "task id %r must look like %s.<n>" % (tid, ws.id))
                    continue
                if prio not in PRIORITIES:
                    self.add("E18", path, i + 1, "priority %r not in %s" % (prio, "|".join(PRIORITIES)))
                tail = RE_TASK_TAIL.match(rest)
                text, dep, blocked = (tail.group(1), tail.group(2), tail.group(3)) if tail else (rest, None, None)
                task = Task(tid, ws.id, prio, text.strip(), split_list(dep or "", ",;"),
                            blocked.strip() if blocked else None, i + 1, self.rel(path))
                if tid in self.tasks:
                    self.add("E05", path, i + 1, "duplicate task %s" % tid)
                    continue
                self.tasks[tid] = task
                ws.tasks.append(tid)

    def load_analyses(self) -> None:
        path = self.research / "analyses.csv"
        for line, row in self.read_csv(path, ANALYSES_HEADER, "E16"):
            aid = row.get("id", "")
            if not RE_ANALYSIS.match(aid):
                self.add("E16", path, line, "id %r must match V2, D<n>[a-z], D1DD<n> or F<n>" % aid)
                continue
            if aid in self.analyses:
                self.add("E05", path, line, "duplicate analysis %s" % aid)
                continue
            self.analyses[aid] = row
            self.analysis_lines[aid] = line

    def load_campaigns(self) -> None:
        path = self.research / "campaigns.csv"
        seen: Set[str] = set()
        for line, row in self.read_csv(path, CAMPAIGNS_HEADER, "E17"):
            ns = row.get("namespace", "")
            if not ns:
                self.add("E17", path, line, "empty namespace")
            elif ns in seen:
                self.add("E17", path, line, "duplicate namespace %r" % ns)
            seen.add(ns)
            if row.get("status") not in CAMPAIGN_STATUS:
                self.add("E17", path, line, "status %r not in %s" % (row.get("status"), "|".join(CAMPAIGN_STATUS)))
            if row.get("relaunch_policy") not in RELAUNCH:
                self.add("E17", path, line, "relaunch_policy %r not in %s" % (row.get("relaunch_policy"), "|".join(RELAUNCH)))
            cmd = row.get("resume_command", "")
            if cmd != "none" and not (cmd.startswith("bash ") or cmd.startswith("python ")):
                self.add("E17", path, line, "resume_command must be 'none' or start with 'bash ' or 'python '")
            self.campaigns.append(row)

    def load_hypotheses(self) -> None:
        path = self.research / "hypotheses.md"
        if not self.need(path):
            return
        current: Optional[Hypothesis] = None
        for i, line in unfenced(enumerate(read_lines(path))):
            if line.startswith("#"):
                current = None
                if line.startswith("## H-"):
                    m = RE_HYP_HEADER.match(line)
                    if not m:
                        self.add("E01", path, i + 1, "malformed hypothesis header; expected '## H-<S0|S1|S2|I|A>-<NN> — <statement>'")
                        continue
                    hid = m.group(1)
                    if hid in self.hyps:
                        self.add("E05", path, i + 1, "duplicate hypothesis %s" % hid)
                        continue
                    current = Hypothesis(hid, m.group(2).strip(), i + 1, {}, {})
                    self.hyps[hid] = current
                continue
            if current is None:
                continue
            m = RE_KEY_LINE.match(line)
            if not m:
                continue
            key, value = m.group(1), m.group(2).strip()
            if key in current.keys:
                self.add("E01", path, i + 1, "duplicate key %r in %s" % (key, current.id))
                continue
            current.keys[key] = parse_value(value) if key in HYP_LISTS else value
            current.key_lines[key] = i + 1
        for h in self.hyps.values():
            for key in HYP_KEYS:
                if key not in h.keys:
                    self.add("E02", path, h.line, "%s misses key %r" % (h.id, key))
            for key in sorted(set(h.keys) - set(HYP_KEYS)):
                self.add("E02", path, h.key_lines[key], "%s has unknown key %r" % (h.id, key))
            for key in HYP_LISTS & set(h.keys):
                if not isinstance(h.keys[key], list):
                    self.add("E02", path, h.key_lines[key], "%s %s must be an inline list [a, b]" % (h.id, key))
            if "stage" in h.keys and h.keys["stage"] not in HYP_STAGES:
                self.add("E02", path, h.key_lines["stage"], "%s stage %r not in %s" % (h.id, h.keys["stage"], "|".join(HYP_STAGES)))
            if "questions" in h.keys and (not h.questions or any(q not in Q_TAGS for q in h.questions)):
                self.add("E02", path, h.key_lines["questions"], "%s questions must be a non-empty subset of %s" % (h.id, ", ".join(Q_TAGS)))
            origin = h.keys.get("origin", "")
            if "origin" in h.keys and not re.match(r"^(canvas|new) \S+", str(origin)):
                self.add("E02", path, h.key_lines["origin"], "%s origin must start with 'canvas <snapshot>' or 'new <date>'" % h.id)
            for key in ("gate_supports", "gate_not"):
                if key in h.keys and not str(h.keys[key]).strip():
                    self.add("E02", path, h.key_lines[key], "%s %s is empty" % (h.id, key))
            seen: Set[str] = set()
            for alt in h.lst("alternatives"):
                if alt in seen:
                    self.add("E05", path, h.key_lines.get("alternatives", h.line), "%s lists %s twice" % (h.id, alt))
                seen.add(alt)

    def load_asks(self) -> None:
        base = self.research / "asks"
        if not base.is_dir():
            return
        for path in sorted(base.glob("*.md")):
            lines = read_lines(path)
            fm = parse_front_matter(lines, path, self.report)
            for key in ASK_KEYS:
                if key not in fm.data:
                    self.add("E02", path, 1, "asks front matter misses %r" % key)
            for key in sorted(set(fm.data) - set(ASK_KEYS) - set(ASK_KEYS_OPTIONAL)):
                self.add("E02", path, fm.lines[key], "unknown asks front-matter key %r" % key)
            checks = (("date", None), ("source", ASK_SOURCES), ("capture", ASK_CAPTURE))
            for key, allowed in checks:
                if key not in fm.data:
                    continue
                bad = not valid_date(fm.data[key]) if allowed is None else fm.data[key] not in allowed
                if bad:
                    self.add("E02", path, fm.lines[key], "bad %s value %r" % (key, fm.data[key]))
            if "asked_by" in fm.data and not RE_ASKED_BY.match(str(fm.data["asked_by"])):
                self.add("E02", path, fm.lines["asked_by"], "asked_by %r is not in the vocabulary" % fm.data["asked_by"])
            file_date = str(fm.data.get("date", ""))
            if valid_date(file_date):
                self.ask_file_dates.append(file_date)
            for i, line in unfenced((j, lines[j]) for j in range(fm.body_start, len(lines))):
                if not line.startswith("- [A-"):
                    continue
                m = RE_ASK_LINE.match(line)
                if not m:
                    self.add("E01", path, i + 1, "malformed ask line; expected '- [A-YYYYMMDD-NN] (asker) \"text\" -> routes'")
                    continue
                aid, asker = m.group(1), (m.group(2) or str(fm.data.get("asked_by", ""))).strip()
                if m.group(2) and not RE_ASKED_BY.match(asker):
                    self.add("E02", path, i + 1, "asker override %r is not in the asked_by vocabulary" % asker)
                if aid in self.asks:
                    self.add("E05", path, i + 1, "duplicate ask %s" % aid)
                    continue
                self.asks[aid] = Ask(aid, self.rel(path), i + 1, asker, m.group(3).strip(),
                                     split_list(m.group(4), ","), file_date)

    def load_devlog(self) -> None:
        tpl = self.devlog_dir / "_TEMPLATE.md"
        if self.need(tpl):
            self.template = tpl
            lines = read_lines(tpl)
            fm = parse_front_matter(lines, tpl, self.report)
            for key in sorted(set(fm.data) - set(ENTRY_KEYS)):
                self.add("E02", tpl, fm.lines[key], "template has unknown key %r" % key)
            heads = [h for h, _, _ in split_sections(lines, fm.body_start)]
            if heads != list(SECTIONS):
                self.add("E06", tpl, 1, "template sections must be exactly: %s" % " | ".join(SECTIONS))
        if not self.devlog_dir.is_dir():
            return
        for ydir in sorted(p for p in self.devlog_dir.iterdir() if p.is_dir() and re.match(r"^\d{4}$", p.name)):
            for path in sorted(ydir.glob("*.md")):
                self.load_entry(path)
        self.entries.sort(key=entry_sort_key)

    def load_entry(self, path: Path) -> None:
        lines = read_lines(path)
        fm = parse_front_matter(lines, path, self.report)
        sections = split_sections(lines, fm.body_start)
        entry = Entry(path.stem, path, self.rel(path), fm.data, fm.lines, lines, fm.body_start, sections)
        m = RE_ENTRY_FILE.match(path.name)
        if not m:
            self.add("E03", path, 0, "file name must be <YYYY-MM-DD>_<slug>.md with slug [a-z0-9-]{1,60}")
        else:
            if not valid_date(m.group(1)):
                self.add("E03", path, 0, "file name date %r is not a valid date" % m.group(1))
            if path.parent.name != m.group(1)[:4]:
                self.add("E03", path, 0, "year directory %r does not match the date year" % path.parent.name)
        if entry.id in self.entry_by_id:
            self.add("E05", path, 1, "duplicate devlog id %s (also %s)" % (entry.id, self.entry_by_id[entry.id].rel))
            return
        self.entry_by_id[entry.id] = entry
        self.entries.append(entry)
        # evidence bullets
        n = 0
        results = unfenced(entry.section("Results"))
        for k, (i, line) in enumerate(results):
            em = RE_EVIDENCE.match(line)
            if em:
                n += 1
                extra: List[str] = []
                for _, nxt in results[k + 1:]:
                    if nxt.strip() and not nxt[0].isspace():
                        break
                    extra.append(nxt)
                while extra and not extra[-1].strip():
                    extra.pop()
                entry.evidence.append(Evidence(entry.id, n, em.group(1), em.group(2), em.group(3).strip(),
                                               extra, i + 1, entry.date, entry.rel))
            elif RE_EVIDENCE_LOOSE.match(line):
                self.add("E03", path, i + 1, "malformed evidence tag; expected top-level '- [H-ID supports|qualifies|contradicts] text'")

    # ----------------------------------------------------------------------- validation
    def validate(self, d: "Derived", ctx: "Context") -> None:
        self.validate_entries(d, ctx)
        self.validate_hypotheses(d)
        self.validate_registry(d, ctx)
        self.validate_refs()
        self.validate_number_free()
        self.validate_time_based(d, ctx)

    def ref_ok(self, token: str) -> bool:
        if token == "THEME":
            return True
        if RE_WS.match(token):
            return token in self.workstreams
        if RE_TASK.match(token):
            return token in self.tasks
        if RE_HID.match(token):
            return token in self.hyps
        if RE_ANALYSIS.match(token):
            return token in self.analyses
        if RE_ALT_ID.match(token):
            return token in self.alts
        if RE_ASK_ID.match(token):
            return token in self.asks
        return False

    def validate_refs(self) -> None:
        for ask in sorted(self.asks.values(), key=lambda a: a.id):
            if not ask.routes:
                self.add("E04", ask.rel, ask.line, "%s has no route tokens" % ask.id)
            for token in ask.routes:
                if token == "THEME" or RE_WS.match(token) or RE_TASK.match(token) or RE_HID.match(token) or RE_ANALYSIS.match(token):
                    if not self.ref_ok(token):
                        self.add("E04", ask.rel, ask.line, "%s routes to unknown %s" % (ask.id, token))
                else:
                    self.add("E04", ask.rel, ask.line, "%s route token %r is not W#, W#.n, an analysis ID, an H-ID or THEME" % (ask.id, token))
        for tid in sorted(self.tasks, key=task_key):
            task = self.tasks[tid]
            for dep in task.depends:
                if dep not in self.tasks:
                    self.add("E04", task.rel, task.line, "%s depends on unknown task %s" % (tid, dep))
        path = self.research / "alternatives.csv"
        for aid in sorted(self.alts):
            for tid in split_list(self.alts[aid].get("typical_tasks", "")):
                if tid not in self.tasks:
                    self.add("E04", path, self.alt_lines[aid], "%s typical_tasks names unknown task %s" % (aid, tid))

    def validate_hypotheses(self, d: "Derived") -> None:
        path = self.research / "hypotheses.md"
        for hid in sorted(self.hyps, key=hyp_key):
            h = self.hyps[hid]
            for key, known, what in (("analyses", self.analyses, "analysis"), ("workstreams", self.workstreams, "workstream"),
                                     ("alternatives", self.alts, "alternative"), ("blocking", self.tasks, "task")):
                for token in h.lst(key):
                    if token not in known:
                        self.add("E04", path, h.key_lines.get(key, h.line), "%s %s names unknown %s %s" % (hid, key, what, token))
            hist = d.verdict_hist.get(hid, [])
            if not hist:
                self.add("E14", path, h.line, "%s has no verdict declaration in any devlog entry" % hid)
                continue
            verdict = hist[-1][2]
            if verdict.startswith("supported_") and not any(ev.role == "supports" for ev in d.evidence.get(hid, [])):
                self.add("E14", path, h.line, "%s is %s but has no current 'supports' evidence bullet" % (hid, verdict))
            if verdict == "supported_publication":
                failed = [name for name, passed in d.gate(hid) if not passed]
                if failed:
                    decl = self.entry_by_id[hist[-1][1]]
                    self.add("E13", decl.path, decl.line_of("verdicts"),
                             "%s=supported_publication fails the publication gate: %s" % (hid, "; ".join(failed)))

    def validate_registry(self, d: "Derived", ctx: "Context") -> None:
        path = self.research / "analyses.csv"
        for aid in sorted(self.analyses, key=analysis_key):
            row, line = self.analyses[aid], self.analysis_lines[aid]
            fam = analysis_family(aid)
            if row.get("family") != fam:
                self.add("E16", path, line, "%s family %r must be %r" % (aid, row.get("family"), fam))
            status = row.get("status", "")
            if status not in REGISTRY_STATUS:
                self.add("E16", path, line, "%s status %r not in %s" % (aid, status, "|".join(REGISTRY_STATUS)))
            if fam in ("D1DD", "F") and row.get("date", "") > CLOSED_SERIES_SINCE:
                self.add("E16", path, line, "%s: the %s series is closed (no new IDs after %s)" % (aid, fam, CLOSED_SERIES_SINCE))
            if aid == "F8" and status != "retired":
                self.add("E16", path, line, "F8 is retired and must never be reused")
            qs = split_list(row.get("questions", ""))
            if any(q not in Q_TAGS for q in qs) or (not qs and status != "planned"):
                self.add("E16", path, line, "%s questions must be ';'-separated tags from %s" % (aid, ", ".join(Q_TAGS)))
            if row.get("asked_by") and not RE_ASKED_BY.match(row["asked_by"]):
                self.add("E16", path, line, "%s asked_by %r is not in the vocabulary" % (aid, row["asked_by"]))
            ws = row.get("workstream", "")
            if ws not in self.workstreams:
                self.add("E16", path, line, "%s workstream %r does not exist under workstreams/" % (aid, ws))
            if row.get("date") and not valid_date(row["date"]):
                self.add("E16", path, line, "%s date %r must be YYYY-MM-DD" % (aid, row["date"]))
            if not row.get("title"):
                self.add("E16", path, line, "%s has no title" % aid)
            for ask in split_list(row.get("asks", "")):
                if ask not in self.asks:
                    self.add("E04", path, line, "%s cites unknown ask %s" % (aid, ask))
            if status not in ("planned", "retired"):
                for col in ("notebook", "code"):
                    for rel in split_list(row.get(col, "")):
                        if not (self.repo / rel).exists():
                            self.add("E16", path, line, "%s %s path %r does not exist (repo-relative)" % (aid, col, rel))
            for col in ("artifact_dir", "findings_md"):
                value = row.get(col, "")
                if value and bad_artifact_path(value):
                    self.add("E08", path, line, "%s %s %r must be relative to the experiment dir" % (aid, col, value))
                elif value and ctx.exp is not None and status not in ("planned", "retired") and not (ctx.exp / value).exists():
                    self.add("W10", path, line, "%s %s %r is missing under the experiment dir" % (aid, col, value))
            if status == "current" and not d.analysis_citers.get(aid):
                self.add("W05", path, line, "%s is current but no devlog entry cites it" % aid)
            if status == "planned" and any(e.status == "done" for e in d.analysis_citers.get(aid, [])):
                self.add("W06", path, line, "%s is planned but cited by a done entry; update its status" % aid)

    def validate_entries(self, d: "Derived", ctx: "Context") -> None:
        protected = [str(p).rstrip("/") for p in self.config.get("protected_paths", []) or []]
        protected_since = str(self.config.get("protected_since", "") or "")
        roots = [str(r).rstrip("/") for r in self.config.get("versioned_slug_roots", []) or []]
        slug_since = str(self.config.get("versioned_slug_rule_since", "") or "")
        owners = {}
        for aid, row in self.analyses.items():
            ad = row.get("artifact_dir", "").rstrip("/")
            if ad and ad not in roots:
                owners.setdefault(ad, set()).add(aid)
        top_level = {p.name for p in self.repo.iterdir() if p.name != "experiments"} if self.repo.is_dir() else set()
        closers: Dict[str, List[Entry]] = {}
        for e in self.entries:
            self.validate_entry_fm(e)
            self.validate_entry_body(e, top_level)
            if e.status == "done":
                for tid in e.lst("closes"):
                    closers.setdefault(tid, []).append(e)
            # artifacts: E08, E11, W10
            analyses = set(e.lst("analyses"))
            for i, line in unfenced(e.section("Artifacts")):
                primary = bool(re.match(r"^[-*+]\s+`?[a-z0-9_.=-]+/", line))
                for token in path_tokens(line):
                    if bad_artifact_path(token):
                        self.add("E08", e.path, i + 1, "artifact path %r must be relative to the experiment dir" % token)
                        continue
                    if RE_TODO.search(line) or re.search(r"\.\.\.|…|[*?<>{}$]", token):
                        continue  # scaffold hints and placeholders (E15 covers unfilled lines)
                    norm = token.rstrip("/")
                    # the backfilled entry that produced them on protected_since itself is exempt
                    if protected_since and e.date >= protected_since and not (e.backfilled and e.date == protected_since):
                        if any(norm == p or norm.startswith(p + "/") for p in protected):
                            self.add("E11", e.path, i + 1, "lists protected path %r (protected since %s)" % (norm, protected_since))
                    if slug_since and e.date >= slug_since and not e.backfilled:
                        for root in roots:
                            if norm == root or norm.startswith(root + "/"):
                                slug = norm[len(root) + 1:].split("/")[0] if norm != root else ""
                                if not RE_VERSIONED.search(slug):
                                    self.add("E11", e.path, i + 1, "slug %r under %s must end in _v<N>" % (slug or "(none)", root))
                    for ad, ids in owners.items():
                        if (norm == ad or norm.startswith(ad + "/")) and not ids & analyses:
                            self.add("E11", e.path, i + 1, "%r is the artifact_dir of %s; list that ID in analyses or use a new slug"
                                     % (ad, ", ".join(sorted(ids, key=analysis_key))))
                    is_primary = primary and token == path_tokens(line)[0]
                    if ctx.exp is not None and (is_primary or "`" + token in line):
                        if re.match(r"^[a-z0-9_.=-]+/", token) and not (ctx.exp / norm).exists():
                            self.add("W10", e.path, i + 1, "artifact %r is missing under the experiment dir" % norm)
        for tid in sorted(closers, key=task_key):
            current = [e for e in closers[tid] if e.id not in d.superseded]
            if len(current) >= 2:
                self.add("E12", current[-1].path, current[-1].line_of("closes"),
                         "%s is closed by %s without supersedes" % (tid, " and ".join(e.id for e in current)))

    def validate_entry_fm(self, e: Entry) -> None:
        fm, path = e.fm, e.path
        if not fm:
            return
        for key in ENTRY_REQUIRED:
            if key not in fm:
                self.add("E02", path, 1, "missing required key %r" % key)
        for key in sorted(set(fm) - set(ENTRY_KEYS)):
            self.add("E02", path, e.line_of(key), "unknown key %r" % key)
        live = {k: v for k, v in fm.items() if not is_todo(v)}
        m = RE_ENTRY_FILE.match(path.name)
        if "id" in live and live["id"] != e.id:
            self.add("E03", path, e.line_of("id"), "id %r must equal the file stem %r" % (live["id"], e.id))
        if "date" in live:
            if not valid_date(live["date"]):
                self.add("E03", path, e.line_of("date"), "date %r must be YYYY-MM-DD" % live["date"])
            elif m and live["date"] != m.group(1):
                self.add("E03", path, e.line_of("date"), "date %s must equal the file name date %s" % (live["date"], m.group(1)))
        for key in ENTRY_LISTS & set(live):
            if not isinstance(live[key], list):
                self.add("E02", path, e.line_of(key), "%s must be an inline list [a, b]" % key)
        for key in ENTRY_BOOLS & set(live):
            if not isinstance(live[key], bool):
                self.add("E02", path, e.line_of(key), "%s must be true or false" % key)
        if "seq" in live and not re.match(r"^\d{1,4}$", str(live["seq"]).strip()):
            self.add("E02", path, e.line_of("seq"), "seq %r must be a non-negative integer (same-day tie-breaker)" % live["seq"])
        enums = (("type", ENTRY_TYPES), ("implemented_by", IMPLEMENTED_BY), ("claim_level", CLAIM_LEVELS),
                 ("status", ENTRY_STATUS), ("compute", COMPUTE), ("c_policy", C_POLICY), ("date_source", DATE_SOURCE))
        for key, allowed in enums:
            if key in live and live[key] not in allowed:
                self.add("E02", path, e.line_of(key), "%s %r not in %s" % (key, live[key], "|".join(allowed)))
        if "asked_by" in live and not RE_ASKED_BY.match(str(live["asked_by"])):
            self.add("E02", path, e.line_of("asked_by"), "asked_by %r is not in the vocabulary" % live["asked_by"])
        if "questions" in live and isinstance(live["questions"], list):
            if not live["questions"] or any(q not in Q_TAGS for q in live["questions"]):
                self.add("E02", path, e.line_of("questions"), "questions must be a non-empty subset of %s" % ", ".join(Q_TAGS))
        for key in ("title", "experiment"):
            if key in live and not str(live[key]).strip():
                self.add("E02", path, e.line_of(key), "%s is empty" % key)
        ws = live.get("workstream")
        if ws is not None:
            if not RE_WS.match(str(ws)):
                self.add("E02", path, e.line_of("workstream"), "workstream %r must be W<n>" % ws)
            elif ws not in self.workstreams:
                self.add("E04", path, e.line_of("workstream"), "unknown workstream %s" % ws)
        # references
        for key, known, what in (("analyses", self.analyses, "analysis"), ("hypotheses", self.hyps, "hypothesis"),
                                 ("closes", self.tasks, "task"), ("advances", self.tasks, "task"),
                                 ("asks", self.asks, "ask"), ("supersedes", self.entry_by_id, "devlog entry")):
            for token in e.lst(key):
                if token not in known:
                    self.add("E04", path, e.line_of(key), "%s names unknown %s %s" % (key, what, token))
                elif key == "supersedes" and entry_sort_key(self.entry_by_id[token]) >= entry_sort_key(e):
                    self.add("E04", path, e.line_of(key), "supersedes target %s is not an earlier entry" % token)
        for token in e.lst("verdicts"):
            vm = RE_VERDICT_TOKEN.match(token)
            if not vm:
                self.add("E02", path, e.line_of("verdicts"), "verdict %r must look like H-ID=verdict" % token)
            elif vm.group(2) not in VERDICTS:
                self.add("E02", path, e.line_of("verdicts"), "verdict %r not in %s" % (vm.group(2), "|".join(VERDICTS)))
            elif vm.group(1) not in self.hyps:
                self.add("E04", path, e.line_of("verdicts"), "verdict for unknown hypothesis %s" % vm.group(1))
        for token in e.lst("alts"):
            am = RE_ALT_TOKEN.match(token)
            if not am:
                self.add("E02", path, e.line_of("alts"), "alt %r must look like H-ID:ALT-ID=open|partial|addressed" % token)
            elif am.group(3) not in ALT_STATES:
                self.add("E02", path, e.line_of("alts"), "alt state %r not in %s" % (am.group(3), "|".join(ALT_STATES)))
            elif am.group(1) not in self.hyps:
                self.add("E04", path, e.line_of("alts"), "alt for unknown hypothesis %s" % am.group(1))
            elif am.group(2) not in self.hyps[am.group(1)].lst("alternatives"):
                self.add("E04", path, e.line_of("alts"), "%s is not listed in %s alternatives" % (am.group(2), am.group(1)))
        for ev in e.evidence:
            if ev.hyp not in self.hyps:
                self.add("E04", path, ev.line, "evidence tag names unknown hypothesis %s" % ev.hyp)
        # provenance
        commit = live.get("commit")
        if commit is not None and not RE_COMMIT.match(str(commit)):
            self.add("E09", path, e.line_of("commit"), "commit %r must be 7-40 hex, 'pending' or 'none'" % commit)
        if fm.get("backfilled") is True and "date_source" not in fm:
            self.add("E09", path, e.line_of("backfilled"), "backfilled entry needs date_source")
        if e.type in ("analysis", "run"):
            for key in ENTRY_RUNLIKE:
                if key not in fm:
                    self.add("E10", path, 1, "%s entry misses %r" % (e.type, key))
            if str(live.get("compute", "")).startswith("screen-"):
                if not any("screen -S" in line for _, line in e.section("Implementation")):
                    self.add("E10", path, e.line_of("compute"), "compute is %s but Implementation has no literal 'screen -S' line" % live["compute"])
            if live.get("training_n_changed") is True and live.get("c_policy") == "global_selected":
                if e.backfilled:
                    self.add("W11", path, e.line_of("c_policy"), "training n changed under global_selected C (recorded as history)")
                else:
                    self.add("E10", path, e.line_of("c_policy"), "training n changed under global_selected C; retune C (R5)")
        # claim level vs verdict (E13, reverse direction)
        if live.get("claim_level") == "publication":
            if not any(t.endswith("=supported_publication") for t in e.lst("verdicts")):
                self.add("E13", path, e.line_of("claim_level"), "claim_level: publication requires a supported_publication verdict in this entry")

    def validate_entry_body(self, e: Entry, top_level: Set[str]) -> None:
        path = e.path
        heads = [h for h, _, _ in e.sections]
        if heads != list(SECTIONS):
            missing = [s for s in SECTIONS if s not in heads]
            extra = [h for h in heads if h not in SECTIONS]
            detail = []
            if missing:
                detail.append("missing: " + ", ".join(missing))
            if extra:
                detail.append("unexpected: " + ", ".join(extra))
            if not detail:
                detail.append("out of order or repeated")
            self.add("E06", path, e.body_start + 1, "sections must be exactly %s (%s)" % (" | ".join(SECTIONS), "; ".join(detail)))
        gate = [re.sub(r"^\s*(?:[-*+]\s+)?(?:\*\*)?", "", line) for _, line in e.section("Claim gate")]
        if "Claim gate" in heads and not (any(g.startswith("Supports (") for g in gate) and any(g.startswith("Does not support:") for g in gate)):
            self.add("E06", path, e.body_start + 1, "Claim gate needs a line starting 'Supports (' and a line starting 'Does not support:'")
        # E15: unfilled TODO markers outside blockquotes, fences and inline code
        todo_lines = []
        for i, line in unfenced(enumerate(e.lines)):
            if line.lstrip().startswith(">"):
                continue
            if RE_TODO.search(RE_BACKTICK.sub("", line)):
                todo_lines.append(i + 1)
        if todo_lines:
            self.add("E15", path, todo_lines[0], "%d unfilled 'TODO:' marker line(s); fill or remove them" % len(todo_lines))
        # W02: evidence bullets and analysis/run Results need numbers
        for ev in e.evidence:
            if not re.search(r"\d", ev.text + " ".join(ev.extra)):
                self.add("W02", path, ev.line, "evidence bullet %s#%d has no digit" % (e.id, ev.n))
        if e.type in ("analysis", "run") and "Results" in heads:
            if not any(re.search(r"\d", line) for _, line in e.section("Results")):
                self.add("W02", path, e.body_start + 1, "Results section has no digit")
        # W03: backticked repo paths
        for i, line in unfenced(enumerate(e.lines)):
            for token in RE_BACKTICK.findall(line):
                token = re.sub(r"(::.*|:\d+(-\d+)?)$", "", token.strip()).rstrip("/")
                if " " in token or "/" not in token or re.search(r"[*?<>{}$]", token):
                    continue
                if token.split("/")[0] in top_level and not (self.repo / token).exists():
                    self.add("W03", path, i + 1, "backticked repo path %r does not exist" % token)

    def validate_number_free(self) -> None:
        if self.theme_lines:
            path = self.research / "THEME.md"
            body = [(i, line) for i, line in enumerate(self.theme_lines) if i >= self.theme_body_start]
            for i, line in unfenced(body):
                if line.lstrip().startswith(">"):
                    continue
                toks = number_tokens(line)
                if toks:
                    self.add("W04", path, i + 1, "number-like token(s) %s in number-free THEME text" % ", ".join(toks))
        path = self.research / "hypotheses.md"
        for hid in sorted(self.hyps, key=hyp_key):
            h = self.hyps[hid]
            for key in sorted(h.keys):
                toks = number_tokens(h.text(key))
                if toks:
                    self.add("W04", path, h.key_lines[key], "%s %s has number-like token(s) %s" % (hid, key, ", ".join(toks)))
        path = self.research / "analyses.csv"
        for aid in sorted(self.analyses, key=analysis_key):
            for col in ("title", "question", "notes"):
                toks = number_tokens(self.analyses[aid].get(col, ""))
                if toks:
                    self.add("W04", path, self.analysis_lines[aid], "%s %s has number-like token(s) %s" % (aid, col, ", ".join(toks)))

    def validate_time_based(self, d: "Derived", ctx: "Context") -> None:
        today = ctx.today
        for e in self.entries:
            ed = to_date(e.date)
            if e.fm.get("commit") == "pending" and ed and (today - ed).days > 14:
                self.add("W01", e.path, e.line_of("commit"), "commit: pending for %d days" % (today - ed).days)
        for wid in sorted(self.workstreams, key=lambda w: int(w[1:])):
            ws = self.workstreams[wid]
            last = to_date(d.ws_last.get(wid, ""))
            if ws.status == "active" and last and (today - last).days > 60:
                self.add("W07", ws.rel, 1, "%s is active but has no devlog entry since %s" % (wid, last.isoformat()))
        for aid in sorted(self.asks):
            ask = self.asks[aid]
            ad = to_date(ask.date)
            if d.ask_state.get(aid) == "open" and ad and (today - ad).days > 30:
                self.add("W08", ask.rel, ask.line, "%s has been open for %d days" % (aid, (today - ad).days))
        if d.theme_queue:
            self.add("W09", self.research / "THEME.md", 1, "THEME review queue has %d entr%s not yet reviewed (after reviewed_through, or after or on last_reviewed and not cited in THEME): %s"
                     % (len(d.theme_queue), "y" if len(d.theme_queue) == 1 else "ies", ", ".join(e.id for e in d.theme_queue)))


def bad_artifact_path(value: str) -> bool:
    return value.startswith(("/", "~", "..", "experiments/")) or any(n in value for n in ABS_NEEDLES)


