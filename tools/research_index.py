def table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> List[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    rows = list(rows)
    for row in rows:
        out.append("| " + " | ".join(cell(c) for c in row) + " |")
    if not rows:
        out.append("| " + " | ".join(["(none)"] + [""] * (len(headers) - 1)) + " |")
    return out


def entry_link(e: Entry, base: Path) -> str:
    return "[%s](%s)" % (e.id, os.path.relpath(str(e.path), str(base)).replace(os.sep, "/"))


