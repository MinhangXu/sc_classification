@dataclasses.dataclass
class Entry:
    id: str
    path: Path
    rel: str
    fm: Dict[str, Any]
    fm_lines: Dict[str, int]
    lines: List[str]
    body_start: int
    sections: List[Tuple[str, int, List[Tuple[int, str]]]]
    evidence: List[Evidence] = dataclasses.field(default_factory=list)

    def val(self, key: str, default: Any = "") -> Any:
        value = self.fm.get(key, default)
        return default if is_todo(value) else value

    def lst(self, key: str) -> List[str]:
        value = self.fm.get(key)
        return [str(v) for v in value] if isinstance(value, list) and not is_todo(value) else []

    @property
    def date(self) -> str:
        value = self.val("date")
        return value if isinstance(value, str) else ""

    @property
    def type(self) -> str:
        return str(self.val("type"))

    @property
    def status(self) -> str:
        return str(self.val("status"))

    @property
    def title(self) -> str:
        return str(self.val("title"))

    @property
    def backfilled(self) -> bool:
        return self.fm.get("backfilled") is True

    def line_of(self, key: str) -> int:
        return self.fm_lines.get(key, 1)

    def section(self, name: str) -> List[Tuple[int, str]]:
        for heading, _, body in self.sections:
            if heading == name:
                return body
        return []


@dataclasses.dataclass
class Hypothesis:
    id: str
    statement: str
    line: int
    keys: Dict[str, Any]
    key_lines: Dict[str, int]

    def lst(self, key: str) -> List[str]:
        value = self.keys.get(key)
        return [str(v) for v in value] if isinstance(value, list) else []

    def text(self, key: str) -> str:
        value = self.keys.get(key, "")
        return fmt_value(value) if not isinstance(value, str) else value

    @property
    def questions(self) -> List[str]:
        return self.lst("questions")


@dataclasses.dataclass
class Task:
    id: str
    ws: str
    priority: str
    text: str
    depends: List[str]
    blocked: Optional[str]
    line: int
    rel: str

    @property
    def short(self) -> str:
        return re.split(r" (?:—|-) done when:", self.text)[0]


@dataclasses.dataclass
class Workstream:
    id: str
    dirname: str
    rel: str
    fm: Dict[str, Any]
    tasks: List[str]

    @property
    def title(self) -> str:
        return str(self.fm.get("title", ""))

    @property
    def status(self) -> str:
        return str(self.fm.get("status", ""))


@dataclasses.dataclass
class Ask:
    id: str
    rel: str
    line: int
    asker: str
    text: str
    routes: List[str]
    file_date: str

    @property
    def date(self) -> str:
        d = self.id[2:10]
        return "%s-%s-%s" % (d[:4], d[4:6], d[6:8])


