def load_studies(repo: Path, study: Optional[str]) -> Optional[List[str]]:
    names = discover(repo)
    if study:
        if study not in names:
            print("unknown study %r; found: %s" % (study, ", ".join(names) or "none"), file=sys.stderr)
            return None
        names = [study]
    return names


def run_check(ctx: Context, names: Sequence[str], experiment_root: Optional[str]) -> int:
    report = Report(ctx.repo)
    for name in names:
        st = Study(ctx.repo, name, report).load()
        d = Derived(st)
        sctx = dataclasses.replace(ctx, exp=resolve_exp(ctx.repo, st, experiment_root))
        if ctx.strict_artifacts and sctx.exp is None:
            report.add("E21", st.research / "study_config.json", 0,
                       "--strict-artifacts, but the experiment dir for %s does not resolve; check --experiment-root, "
                       "SC_EXPERIMENT_ROOT and SC_EXPERIMENT_ID (python -m sc_classification.utils.paths)" % name)
        st.validate(d, sctx)
        for path, text in generated(st, d):
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                diff = list(difflib.unified_diff(current.split("\n"), text.split("\n"), "on disk", "expected", n=0, lineterm=""))
                report.add("E20", path, 0, "generated file is stale; %s" % WRITE_HINT)
                report.stale.append((report.rel(path), "\n".join(diff[:24] + (["..."] if len(diff) > 24 else []))))
    lint_absolute_paths(ctx.repo, names, report)

    def is_error(issue: Issue) -> bool:
        if issue.code.startswith("E"):
            return True
        if issue.code == "W10" and ctx.strict_artifacts:
            return True
        return ctx.strict and issue.code not in STRICT_EXEMPT

    issues = sorted(set(report.issues), key=Issue.sort_key)
    errors = [i for i in issues if is_error(i) and i.code != "E20"]
    warnings = [i for i in issues if not is_error(i)]
    stale = [i for i in issues if i.code == "E20"]
    for issue in errors + stale:
        print(issue.render())
    for rel, diff in report.stale:
        if diff:
            print("--- %s: on disk vs expected\n%s" % (rel, diff))
    for issue in warnings:
        print(issue.render(), file=sys.stderr)
    print("check: %d error(s), %d stale file(s), %d warning(s) in %s" % (len(errors), len(stale), len(warnings), ", ".join(names)))
    if errors:
        return 1
    return 3 if stale else 0


def cmd_write(ctx: Context, names: Sequence[str], experiment_root: Optional[str]) -> int:
    for name in names:
        st = Study(ctx.repo, name, Report(ctx.repo)).load()
        d = Derived(st)
        for path, text in generated(st, d):
            changed = atomic_write(path, text)
            print("%s %s" % ("wrote" if changed else "unchanged", Report(ctx.repo).rel(path)))
    return run_check(ctx, names, experiment_root)


def pick_study(repo: Path, study: Optional[str]) -> Optional[Study]:
    names = load_studies(repo, study)
    if names is None:
        return None
    if len(names) != 1:
        print("pass --study; found: %s" % (", ".join(names) or "none"), file=sys.stderr)
        return None
    return Study(repo, names[0], Report(repo)).load()


def cmd_new_entry(repo: Path, args: argparse.Namespace, today: datetime.date) -> int:
    if not RE_SLUG.match(args.slug):
        print("slug must match [a-z0-9-]{1,60}", file=sys.stderr)
        return 2
    date = args.date or today.isoformat()
    if not valid_date(date):
        print("--date must be YYYY-MM-DD", file=sys.stderr)
        return 2
    if args.type not in ENTRY_TYPES:
        print("--type must be one of %s" % ", ".join(ENTRY_TYPES), file=sys.stderr)
        return 2
    st = pick_study(repo, args.study)
    if st is None:
        return 2
    problems = []
    if args.workstream not in st.workstreams:
        problems.append("unknown workstream %s" % args.workstream)
    problems += ["unknown analysis %s" % a for a in args.analyses if a not in st.analyses]
    problems += ["unknown ask %s" % a for a in args.asks if a not in st.asks]
    if st.template is None:
        problems.append("missing %s" % st.rel(st.devlog_dir / "_TEMPLATE.md"))
    if problems:
        print("new-entry: " + "; ".join(problems), file=sys.stderr)
        return 1
    eid = "%s_%s" % (date, args.slug)
    path = st.devlog_dir / date[:4] / (eid + ".md")
    if path.exists() or eid in st.entry_by_id:
        print("new-entry: %s already exists; entries are append-only" % st.rel(path), file=sys.stderr)
        return 1
    head_out = git(repo, "rev-parse", "--short", "HEAD")
    status_out = git(repo, "status", "--porcelain")
    prefill: Dict[str, Optional[str]] = {
        "id": eid, "date": date, "type": args.type, "workstream": args.workstream,
        "analyses": fmt_value(list(args.analyses)), "asks": fmt_value(list(args.asks)),
        "experiment": st.canonical_id or "none", "commit": "pending", "backfilled": "false", "date_source": "authored",
        "run_head": head_out.strip() if head_out and head_out.strip() else None,
        "dirty_run": fmt_value(bool(status_out.strip())) if status_out is not None else None,
    }
    lines = read_lines(st.template)  # type: ignore[arg-type]
    out: List[str] = []
    in_fm = False
    for i, line in enumerate(lines):
        if i == 0 and line.rstrip() == "---":
            in_fm = True
        elif in_fm and line.rstrip() == "---":
            in_fm = False
        elif in_fm:
            m = RE_FM_LINE.match(line)
            key = m.group(1) if m else None
            if key in ENTRY_RUNLIKE and args.type not in ("analysis", "run"):
                continue
            if key in prefill:
                if prefill[key] is None:
                    continue
                line = "%s: %s" % (key, prefill[key])
        out.append(line)
    text = "\n".join(out)
    if not text.endswith("\n"):
        text += "\n"
    atomic_write(path, text)
    print(st.rel(path))
    return 0


def cmd_reserve_id(repo: Path, args: argparse.Namespace, today: datetime.date) -> int:
    qs = split_list(args.questions or "")
    if any(q not in Q_TAGS for q in qs):
        print("--questions must be ';'-separated tags from %s" % ", ".join(Q_TAGS), file=sys.stderr)
        return 2
    if args.slug and not re.match(r"^[a-z0-9_]+_v\d+$", args.slug):
        print("--slug must be lowercase [a-z0-9_] and end in _v<N>", file=sys.stderr)
        return 2
    if not args.title.strip():
        print("--title must not be empty", file=sys.stderr)
        return 2
    date = args.date or today.isoformat()
    if not valid_date(date):
        print("--date must be YYYY-MM-DD", file=sys.stderr)
        return 2
    st = pick_study(repo, args.study)
    if st is None:
        return 2
    path = st.research / "analyses.csv"
    if args.workstream not in st.workstreams or not path.is_file():
        print("reserve-id: unknown workstream %s or missing %s" % (args.workstream, st.rel(path)), file=sys.stderr)
        return 1
    new_id = Derived(st).next_d
    roots = [str(r).rstrip("/") for r in st.config.get("versioned_slug_roots", []) or []]
    artifact_dir = "%s/%s" % (roots[0] if roots else "analysis/scorecards/stage2_diagnostic", args.slug) if args.slug else ""
    asks = split_list(args.asks or "")
    unknown = [a for a in asks if a not in st.asks]
    if unknown:
        print("reserve-id: unknown ask id(s) %s" % ", ".join(unknown), file=sys.stderr)
        return 1
    code = split_list(args.code or "")
    if any(bad_artifact_path(c) or c.startswith("/") for c in code):
        print("--code paths must be repo-relative", file=sys.stderr)
        return 2
    findings_md = (args.findings_md or "").strip()
    if findings_md and "/" not in findings_md and artifact_dir:
        findings_md = "%s/%s" % (artifact_dir, findings_md)
    if findings_md and bad_artifact_path(findings_md):
        print("--findings-md must be relative to the experiment dir (or a file name inside --slug)", file=sys.stderr)
        return 2
    row = {"id": new_id, "family": "D", "title": args.title.strip(), "question": (args.question or "").strip(),
           "questions": ";".join(qs), "asked_by": args.asked_by, "asks": ";".join(asks), "workstream": args.workstream,
           "notebook": "", "code": ";".join(code), "experiment_id": st.canonical_id, "artifact_dir": artifact_dir,
           "findings_md": findings_md, "figure_prefix": new_id, "date": date, "status": "planned", "notes": ""}
    buf = io.StringIO()
    csv.writer(buf, lineterminator="").writerow([row[k] for k in ANALYSES_HEADER])
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    reader = csv.reader(io.StringIO(text))
    next(reader, None)
    insert_at = reader.line_num
    for rec in reader:
        if rec and analysis_family(rec[0]) in ("V2", "D"):
            insert_at = reader.line_num
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    lines.insert(insert_at, buf.getvalue())
    atomic_write(path, "\n".join(lines) + "\n")
    print(new_id)
    return 0


def cmd_show(repo: Path, args: argparse.Namespace) -> int:
    st = pick_study(repo, args.study)
    if st is None:
        return 2
    d = Derived(st)
    key = args.id.strip()
    out: List[str] = []

    def ent(e: Entry) -> str:
        return "%s  %s  (%s, %s, %s)  %s" % (e.date, e.id, e.type, e.status, e.val("workstream"), e.title)

    def asks_routed(token: str) -> List[str]:
        return ["  %s (%s) %s" % (a.id, d.ask_state.get(a.id), trunc(a.text, 100)) for a in sorted(st.asks.values(), key=lambda a: a.id)
                if token in a.routes]

    def git_lines(paths: Iterable[str]) -> List[str]:
        res = []
        for rel in paths:
            info = git(repo, "log", "-1", "--date=short", "--format=%h %ad %s", "--", rel)
            res.append("  %s: %s" % (rel, (info or "").strip() or "(no commit)"))
        return res

    def section(title: str, lines: List[str]) -> None:
        out.extend(["", title + ":"] + (lines or ["  (none)"]))

    if key in st.analyses:
        row = st.analyses[key]
        out.append("%s  %s  [analysis registry, %s]" % (key, row.get("title", ""), st.rel(st.research / "analyses.csv")))
        out += ["  %s: %s" % (k, row.get(k, "")) for k in ANALYSES_HEADER[1:]]
        section("Cited by devlog entries", ["  " + ent(e) for e in d.analysis_citers.get(key, [])])
        section("Listed by hypotheses", ["  %s (%s) %s" % (h, d.verdict(h)[2], trunc(st.hyps[h].statement, 100)) for h in d.analysis_hyps.get(key, [])])
        section("Asks routed here", asks_routed(key))
        if args.git:
            section("git", git_lines(split_list(row.get("notebook", "")) + split_list(row.get("code", ""))))
    elif key in st.hyps:
        h = st.hyps[key]
        vdate, vid, verdict = d.verdict(key)
        out.append("%s — %s  [%s:%d]" % (key, h.statement, st.rel(st.research / "hypotheses.md"), h.line))
        out += ["  %s: %s" % (k, h.text(k)) for k in HYP_KEYS if k in h.keys]
        out += ["", "Verdict: %s (%s, %s)" % (verdict, vdate or "-", vid or "no declaration")]
        section("Verdict history", ["  %s %s  %s" % (dt, v, i) for dt, i, v in d.verdict_hist.get(key, [])])
        section("Current evidence", ["  [%s] %s#%d (%s): %s" % (ev.role, ev.entry_id, ev.n, ev.date, trunc(ev.text, 140)) for ev in d.evidence.get(key, [])])
        section("Alternatives", ["  %s (%s) %s" % (a, d.alt_state(key, a), trunc(st.alts.get(a, {}).get("reviewer_question", ""), 100)) for a in h.lst("alternatives")])
        section("Blocking tasks", ["  %s (%s) %s" % (t, d.task_state.get(t, "unknown"), trunc(st.tasks[t].short, 100) if t in st.tasks else "") for t in h.lst("blocking")])
        section("Publication gate", ["  %s: %s" % ("pass" if ok else "fail", name) for name, ok in d.gate(key)])
        section("Asks routed here", asks_routed(key))
        section("Citing entries", ["  " + ent(e) for e in d.hyp_citers.get(key, [])])
    elif key in st.workstreams:
        ws = st.workstreams[key]
        out.append("%s  %s  [%s]" % (key, ws.title, ws.rel))
        out += ["  %s: %s" % (k, fmt_value(ws.fm.get(k, ""))) for k in WS_KEYS[2:]]
        out.append("  last devlog date: %s" % d.ws_last.get(key, "-"))
        section("Tasks", ["  %s (%s, %s) %s" % (t, st.tasks[t].priority, d.task_state.get(t), trunc(st.tasks[t].short, 100)) for t in sorted(ws.tasks, key=task_key)])
        section("Devlog entries", ["  " + ent(e) for e in d.ws_entries.get(key, [])])
        section("Asks routed here", asks_routed(key))
        if args.git:
            section("git", git_lines([ws.rel]))
    elif key in st.tasks:
        task = st.tasks[key]
        out.append("%s (%s, %s)  %s  [%s:%d]" % (key, task.priority, d.task_state.get(key), task.text, task.rel, task.line))
        out.append("  depends: %s" % (", ".join("%s (%s)" % (t, "met" if d.task_state.get(t) == "done" else "unmet") for t in task.depends) or "none"))
        out.append("  blocked: %s" % (task.blocked or "no"))
        section("Closing or advancing entries", ["  " + ent(e) + ("  [closes]" if key in e.lst("closes") else "  [advances]") for e in d.task_citers.get(key, [])])
        section("Hypotheses blocked on it", ["  %s (%s)" % (h, d.verdict(h)[2]) for h in sorted(st.hyps, key=hyp_key) if key in st.hyps[h].lst("blocking")])
        section("Alternatives it addresses", ["  " + a for a in sorted(st.alts) if key in split_list(st.alts[a].get("typical_tasks", ""))])
        section("Asks routed here", asks_routed(key))
    elif key in st.asks:
        ask = st.asks[key]
        out.append("%s (%s)  asked_by %s  [%s:%d]" % (key, d.ask_state.get(key), ask.asker, ask.rel, ask.line))
        out.append("  %s" % ask.text)
        section("Routes", ["  %s%s" % (r, " (%s)" % d.task_state.get(r) if r in st.tasks else "") for r in ask.routes])
        section("Citing entries", ["  " + ent(e) for e in d.ask_citers.get(key, [])])
    elif key in st.alts:
        row = st.alts[key]
        out.append("%s  %s  [%s]" % (key, row.get("name", ""), st.rel(st.research / "alternatives.csv")))
        out += ["  %s: %s" % (k, row.get(k, "")) for k in ALT_HEADER[2:]]
        section("Hypotheses", ["  %s (%s): %s" % (h, d.verdict(h)[2], d.alt_state(h, key)) for h in sorted(st.hyps, key=hyp_key) if key in st.hyps[h].lst("alternatives")])
        section("Typical tasks", ["  %s (%s)" % (t, d.task_state.get(t, "unknown")) for t in split_list(row.get("typical_tasks", ""))])
    elif key in st.entry_by_id:
        e = st.entry_by_id[key]
        out.append("%s  [%s]" % (key, e.rel))
        out += ["  %s: %s" % (k, fmt_value(e.fm[k])) for k in ENTRY_KEYS if k in e.fm]
        section("Evidence", ["  %s#%d [%s %s] %s" % (key, ev.n, ev.hyp, ev.role, trunc(ev.text, 140)) for ev in e.evidence])
        section("Superseded by", ["  " + s for s in d.superseded_by.get(key, [])])
        if args.git:
            section("git", git_lines([e.rel]))
    else:
        known = list(st.analyses) + list(st.hyps) + list(st.workstreams) + list(st.tasks) + list(st.asks) + list(st.alts) + list(st.entry_by_id)
        close = difflib.get_close_matches(key, known, n=5)
        print("show: unknown id %r%s" % (key, "; did you mean %s?" % ", ".join(close) if close else ""), file=sys.stderr)
        return 1
    print("\n".join(out))
    return 0


def cmd_portability(repo: Path) -> int:
    overlay = set(overlay_files(repo, discover(repo)))
    hits = []
    for top in ("scripts", "src", "tests"):
        for path in walk_files(repo / top):
            if path.suffix not in PORTABILITY_EXTS or path in overlay:
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            count = sum(1 for line in text.split("\n") if any(n in line for n in PORTABILITY_NEEDLES))
            if count:
                hits.append((path.relative_to(repo).as_posix(), count))
    for rel, count in hits:
        print("%s  %d line(s)" % (rel, count))
    print("portability: %d legacy file(s) under scripts/, src/ and tests/ embed absolute home paths "
          "(listed on demand, never rewritten; see AGENTS.md)" % len(hits))
    return 0


